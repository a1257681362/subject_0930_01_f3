-- ============================================================================
-- 路线温区分段（V2 / cold-chain-2）
-- 设计要点：
-- 1. 一条运输路线一个主档（t_cc_route），按“季节”维护各自的版本序列；
--    版本只追加（t_cc_route_version），状态 DRAFT / EFFECTIVE / SUPERSEDED / REVOKED。
-- 2. 每个版本由若干相邻温区分段组成（t_cc_route_segment）：分段按里程 [from_km, to_km)
--    首尾相接覆盖 0 ~ total_km，既不能有空档也不能重叠；每段指定允许温区、缓冲时长（分钟）
--    与责任人。分段行随版本只追加，历史版本行永不修改——已派车批次按快照核对。
-- 3. 派车只登记路线；发运（批次开始执行）瞬间按“当前季节 + 当前时间”选取生效版本，把其全部分段
--    逐段复制为批次快照（t_cc_route_segment_snap）；派车后发运前发布的新版本仍作用于该批，
--    发运后版本热替换/撤回与在途批次无关。
-- 4. 发布是热替换：新草稿发布时把同季节当前生效版本置 SUPERSEDED；新版本只影响此后派车的
--    未发运批次，已经执行（已派车/在途/签收）的批次继续引用派车时的原快照。
-- 5. 撤回只能撤销“尚未生效”的版本（DRAFT，或已到生效时间窗但从未被批次引用的版本）；
--    已被任一批次引用固化快照的版本不可撤回。
-- 6. 发布前必须展示与当前生效版本的分段差异（ADDED/REMOVED/MODIFIED/UNCHANGED）。
-- ============================================================================

CREATE SEQUENCE IF NOT EXISTS seq_cc_route_no START WITH 30000001 INCREMENT BY 1;

-- 运输路线主档（一条路线一行；同一季节的版本挂在同一 route_id 下）
CREATE TABLE IF NOT EXISTS t_cc_route (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_no     VARCHAR(32)  NOT NULL,                -- 路线编号，序列生成，稳定唯一
    route_name   VARCHAR(128) NOT NULL,                -- 路线名称（如 上海中心仓-杭州一院）
    origin       VARCHAR(128),                         -- 起点
    destination  VARCHAR(128),                         -- 终点
    total_km     DECIMAL(8,2) NOT NULL,                -- 路线总里程，分段必须连续覆盖到该值
    status       VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE', -- ACTIVE / REVOKED
    remark       VARCHAR(255),
    create_by    BIGINT,
    create_time  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by    BIGINT,
    update_time  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_cc_route_no UNIQUE (route_no)
);

-- 路线季节版本（按季节各成版本序列；版本行只追加，状态机见类注释）
CREATE TABLE IF NOT EXISTS t_cc_route_version (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id       BIGINT       NOT NULL,
    season         VARCHAR(16)  NOT NULL,              -- SPRING/SUMMER/AUTUMN/WINTER/GENERAL
    version_no     INT          NOT NULL,              -- 同路线同季节内从 1 递增
    effective_from TIMESTAMP,                          -- 生效起点（可晚于发布时间=预约生效）
    effective_to   TIMESTAMP,                          -- 生效终点（空表示长期有效）
    publish_time   TIMESTAMP,                          -- 实际发布时间（DRAFT 时为空）
    change_reason  VARCHAR(255),
    status         VARCHAR(16)  NOT NULL DEFAULT 'DRAFT', -- DRAFT/EFFECTIVE/SUPERSEDED/REVOKED
    create_by      BIGINT,
    create_time    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by      BIGINT,
    update_time    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_cc_route_ver UNIQUE (route_id, season, version_no)
);
CREATE INDEX IF NOT EXISTS idx_cc_route_ver_pick ON t_cc_route_version (route_id, season, status);

-- 路线温区分段（属于某个季节版本；随版本只追加，永不修改/删除）
CREATE TABLE IF NOT EXISTS t_cc_route_segment (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_id      BIGINT       NOT NULL,
    segment_seq     INT          NOT NULL,             -- 段序号，从 1 按里程递增
    from_km         DECIMAL(8,2) NOT NULL,             -- 段起点公里标（含）
    to_km           DECIMAL(8,2) NOT NULL,             -- 段终点公里标（不含），末段到 total_km
    temp_min        DECIMAL(5,2) NOT NULL,             -- 本段允许温度下限 ℃
    temp_max        DECIMAL(5,2) NOT NULL,             -- 本段允许温度上限 ℃
    buffer_minutes  INT          NOT NULL,             -- 越限缓冲时长（分钟）：连续越限超过它才开异常
    owner_name      VARCHAR(64)  NOT NULL,             -- 本段责任人
    owner_phone     VARCHAR(32),
    remark          VARCHAR(255),
    create_by       BIGINT,
    create_time     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_cc_seg_km CHECK (from_km < to_km),
    CONSTRAINT ck_cc_seg_temp CHECK (temp_min <= temp_max),
    CONSTRAINT ck_cc_seg_buffer CHECK (buffer_minutes >= 0)
);
CREATE INDEX IF NOT EXISTS idx_cc_seg_version ON t_cc_route_segment (version_id, segment_seq);

-- 批次路线分段快照（派车时从选定版本逐段固化；批次温度判定/追溯一律以快照为准）
CREATE TABLE IF NOT EXISTS t_cc_route_segment_snap (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id        BIGINT       NOT NULL,
    segment_seq     INT          NOT NULL,
    from_km         DECIMAL(8,2) NOT NULL,
    to_km           DECIMAL(8,2) NOT NULL,
    temp_min        DECIMAL(5,2) NOT NULL,
    temp_max        DECIMAL(5,2) NOT NULL,
    buffer_minutes  INT          NOT NULL,
    owner_name      VARCHAR(64)  NOT NULL,
    owner_phone     VARCHAR(32),
    remark          VARCHAR(255),
    create_by       BIGINT,
    create_time     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_cc_segsnap_batch ON t_cc_route_segment_snap (batch_id, segment_seq);

-- 运输批次补充“路线引用”：派车登记路线、发运时选定路线季节版本并固化全部分段快照
ALTER TABLE t_cc_transport_batch ADD COLUMN IF NOT EXISTS route_id BIGINT;
ALTER TABLE t_cc_transport_batch ADD COLUMN IF NOT EXISTS route_version_id BIGINT;
ALTER TABLE t_cc_transport_batch ADD COLUMN IF NOT EXISTS route_season VARCHAR(16);
ALTER TABLE t_cc_transport_batch ADD COLUMN IF NOT EXISTS route_version_no INT;

-- 温度留痕补充分段定位（按里程命中的快照段；无路线批次为空，回退全程单一温区）
ALTER TABLE t_cc_temperature_log ADD COLUMN IF NOT EXISTS mileage_km DECIMAL(8,2);
ALTER TABLE t_cc_temperature_log ADD COLUMN IF NOT EXISTS segment_seq INT;

-- 异常事件补充分段定位（越限发生在哪一段，便于追责任人）
ALTER TABLE t_cc_exception ADD COLUMN IF NOT EXISTS segment_seq INT;

-- ============================================================================
-- 车载温度探头校准凭证管理（V3 / cold-chain-3）
-- 设计要点：
-- 1. 探头建档（t_cc_temperature_probe）登记序列号（全局唯一）、量程上下限、校准机构与
--    校准有效期；证书逐次上传（t_cc_probe_certificate），落库内容字节并计算 SHA-256 摘要，
--    证书行只追加；作废只置 VOID 状态（记录作废原因/时间/人），不删除文件。
-- 2. 发运前必须在“车载探头校准凭证关联”把仍在有效期内的探头绑定到未发运批次
--    （t_cc_batch_probe_binding）。同一批次同一时刻至多一条 ACTIVE 绑定（库级唯一），
--    因此同一请求重复提交只返回既有绑定，绝不产生第二条结果。
-- 3. 替换探头：旧 ACTIVE 绑定在同一事务内置 REPLACED（previous_binding_id 串起前后关系），
--    新 ACTIVE 绑定指回前序绑定；已落库的温度留痕保留当时实际采集探头 probe_id，永不回写。
-- 4. 有效期为硬约束：建档可登记过期探头，但“凭证关联”与发运双入口拦截过期/作废/无有效证书
--    的设备；温度上报瞬间再次校验当前绑定探头仍然有效，证书一旦过期/作废，在途上报即被拦截。
-- 5. 证书上传/下载/作废与绑定/替换/解绑全部写 t_cc_op_log（实体类型 PROBE），
--    其中下载与作废逐次写审计流水。
-- ============================================================================

CREATE SEQUENCE IF NOT EXISTS seq_cc_probe_no START WITH 40000001 INCREMENT BY 1;

-- 车载温度探头档案（一个物理探头一行，序列号全局唯一；状态 ACTIVE/REVOKED）
CREATE TABLE IF NOT EXISTS t_cc_temperature_probe (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    probe_no            VARCHAR(32)  NOT NULL,               -- 探头编号，序列生成，稳定唯一
    serial_no           VARCHAR(64)  NOT NULL,               -- 设备出厂序列号，全局唯一
    model               VARCHAR(64),                         -- 探头型号
    measure_min         DECIMAL(5,2) NOT NULL,               -- 量程下限 ℃
    measure_max         DECIMAL(5,2) NOT NULL,               -- 量程上限 ℃
    calib_org           VARCHAR(128) NOT NULL,               -- 校准机构
    valid_until         TIMESTAMP    NOT NULL,               -- 校准有效期至（建档登记的当前凭证有效期）
    status              VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE', -- ACTIVE / REVOKED
    remark              VARCHAR(255),
    create_by           BIGINT,
    create_time         TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by           BIGINT,
    update_time         TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_cc_probe_no UNIQUE (probe_no),
    CONSTRAINT uk_cc_probe_serial UNIQUE (serial_no),
    CONSTRAINT ck_cc_probe_range CHECK (measure_min < measure_max)
);

-- 探头校准证书（每次上传追加一行；作废只置状态不删行/不删文件）
CREATE TABLE IF NOT EXISTS t_cc_probe_certificate (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    probe_id        BIGINT       NOT NULL,                   -- 所属探头
    cert_no         VARCHAR(64),                             -- 证书编号（校准机构出具）
    file_name       VARCHAR(255) NOT NULL,                   -- 原始文件名
    content_type    VARCHAR(128),                            -- 上传时的 MIME 类型
    file_size       BIGINT       NOT NULL,                   -- 文件字节数
    sha256          VARCHAR(64)  NOT NULL,                   -- 上传后对内容计算的 SHA-256 摘要
    content         BLOB         NOT NULL,                   -- 证书文件内容（本地留存，供下载）
    valid_from      TIMESTAMP,                               -- 校准日期/生效起点
    valid_until     TIMESTAMP    NOT NULL,                   -- 有效期至
    status          VARCHAR(16)  NOT NULL DEFAULT 'VALID',   -- VALID 在库可用 / VOID 已作废
    void_reason     VARCHAR(255),                            -- 作废原因
    void_time       TIMESTAMP,                               -- 作废时间
    void_by         BIGINT,                                  -- 作废人
    create_by       BIGINT,
    create_time     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_cc_cert_time CHECK (valid_from IS NULL OR valid_from <= valid_until)
);
CREATE INDEX IF NOT EXISTS idx_cc_cert_probe ON t_cc_probe_certificate (probe_id, id);

-- 批次-探头绑定关系（替换留前后关系；每批同时只有一条 ACTIVE，由库级唯一约束保证幂等）
CREATE TABLE IF NOT EXISTS t_cc_batch_probe_binding (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id             BIGINT       NOT NULL,
    probe_id             BIGINT       NOT NULL,
    cert_id              BIGINT       NOT NULL,              -- 绑定时采信的有效证书
    bind_time            TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    unbind_time          TIMESTAMP,                          -- 主动解绑时间（未发生替换的移除）
    replace_time         TIMESTAMP,                          -- 被新探头替换的时间
    previous_binding_id  BIGINT,                             -- 前序绑定（替换链条）
    reason               VARCHAR(255),                       -- 解绑/替换原因
    status               VARCHAR(16) NOT NULL DEFAULT 'ACTIVE', -- ACTIVE / REPLACED / UNBOUND
    -- 仅 ACTIVE 行取 batch_id，其余为 NULL：唯一约束在库级保证“每批至多一条活跃绑定”，
    -- REPLACED/UNBOUND 历史行（键为 NULL，NULL 互不相等）不受数量限制。
    active_batch_key     BIGINT GENERATED ALWAYS AS (CASE WHEN status = 'ACTIVE' THEN batch_id ELSE NULL END),
    create_by            BIGINT,
    create_time          TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_by            BIGINT,
    update_time          TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_cc_active_binding UNIQUE (active_batch_key)
);
CREATE INDEX IF NOT EXISTS idx_cc_binding_probe ON t_cc_batch_probe_binding (probe_id);


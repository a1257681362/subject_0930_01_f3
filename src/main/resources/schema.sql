-- ============================================================================
-- 冷链药品运输台账（V1）
-- 设计要点：
-- 1. 药品档案采用“一档案 + 全量版本行”：变更只追加新版本，旧版本行永不修改，
--    已派车的运输批次按派车时固化的快照版本完成核对。
-- 2. 运输批次冗余档案快照（批准文号/储存温区/包装规格 + 版本号），档案后续变更不影响在途批次。
-- 3. 温度记录、异常事件、异常凭证均为追加式（只 INSERT，不 UPDATE/DELETE）。
-- 4. 撤回只做状态作废标记，不删除任何原始记录。
-- 5. 所有关键动作写 t_cc_op_log，统一留存操作者与时间。
-- 6. 批次号由 H2 SEQUENCE 生成，稳定、单调、数据库层唯一，重启不复用。
-- ============================================================================

